/** First match; callers only use it for elements that are known to exist. */
export const $ = <T extends Element = HTMLElement>(s: string, el: ParentNode = document): T => el.querySelector(s) as T;
export const $$ = <T extends Element = HTMLElement>(s: string, el: ParentNode = document): T[] => [...el.querySelectorAll<T>(s)];

export const esc = (s: unknown): string =>
  String(s ?? '').replace(/[&<>"']/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[ch]!);

/** `data-*` lookups from event targets, which may be text nodes or SVG parts. */
export const closest = <T extends HTMLElement = HTMLElement>(t: EventTarget | null, sel: string): T | null =>
  t instanceof Element ? (t.closest(sel) as T | null) : null;

export const narrowQuery = matchMedia('(max-width: 820px)');
export const isNarrow = (): boolean => narrowQuery.matches;
export const coarseQuery = matchMedia('(hover: none)');
